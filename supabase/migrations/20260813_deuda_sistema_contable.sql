create or replace function public.tarifa_sistema_por_unidad(p_precio numeric)
returns numeric
language sql
immutable
strict
set search_path = public, pg_temp
as $function$
  select case
    when p_precio <= 60 then 0.50
    when p_precio <= 150 then 1.00
    when p_precio <= 399 then 2.00
    when p_precio <= 999 then 3.00
    else 5.00
  end::numeric(12,2);
$function$;

create or replace function public.materializar_deuda_sistema_pedido(p_pedido_id uuid)
returns integer
language plpgsql
security definer
set search_path = public, pg_temp
as $function$
declare
  v_pedido public.pedidos%rowtype;
  v_lineas integer := 0;
  v_catalogo_total numeric := 0;
  v_neto numeric := 0;
  v_precio_unit numeric;
  v_tarifa_unit numeric;
  v_incidencia text;
  v_formato_invalido boolean := false;
  r record;
begin
  select * into v_pedido from public.pedidos where id = p_pedido_id for update;
  if not found then return 0; end if;
  perform pg_advisory_xact_lock(hashtext('pth_liquidar_deuda_sistema'));
  if v_pedido.estado <> 'Entregado' then return 0; end if;
  if coalesce(lower(trim(v_pedido.pago_sistema)), 'pendiente') = 'pagado' then return 0; end if;

  if exists (select 1 from public.deuda_sistema_detalle where pedido_id = p_pedido_id) then
    return 0;
  end if;

  create temporary table if not exists pg_temp.pth_deuda_lineas (
    linea integer,
    cantidad integer,
    producto text,
    precio_catalogo numeric
  ) on commit drop;
  truncate pg_temp.pth_deuda_lineas;

  insert into pg_temp.pth_deuda_lineas(linea,cantidad,producto,precio_catalogo)
  select
    s.ord::integer,
    greatest(1, (q.m)[1]::integer),
    n.nombre,
    pr.precio::numeric
  from regexp_split_to_table(
    coalesce(v_pedido.producto,''),
    '\][[:space:]]*\+[[:space:]]*'
  ) with ordinality as s(segment,ord)
  cross join lateral (
    select regexp_match(s.segment, '^\s*([0-9]+)x\s+', 'i') m
  ) q
  cross join lateral (
    select trim(regexp_replace(
      regexp_replace(s.segment, '^\s*[0-9]+x\s+', '', 'i'),
      '\s*\[(USD|CUP)\]?\s*$', '', 'i'
    )) nombre
  ) n
  left join lateral (
    select p.precio
    from public.productos p
    where lower(regexp_replace(trim(p.nombre), '[[:space:]]+', ' ', 'g')) =
          lower(regexp_replace(n.nombre, '[[:space:]]+', ' ', 'g'))
    order by
      case when lower(trim(coalesce(p.proveedor,''))) = lower(trim(coalesce(v_pedido.proveedor,''))) then 0 else 1 end,
      case when upper(coalesce(p.disponible,'')) = 'SI' then 0 else 1 end
    limit 1
  ) pr on true
  where q.m is not null;

  if not exists (select 1 from pg_temp.pth_deuda_lineas) then
    v_formato_invalido := true;
    insert into pg_temp.pth_deuda_lineas(linea,cantidad,producto,precio_catalogo)
    values (
      1,
      greatest(1, coalesce((regexp_match(coalesce(v_pedido.producto,''), '^\s*([0-9]+)x', 'i'))[1]::integer,1)),
      trim(regexp_replace(coalesce(v_pedido.producto,'Producto sin nombre'), '^\s*[0-9]+x\s*|\s*\[[^]]+\]\s*$', '', 'gi')),
      null
    );
  end if;

  select count(*), coalesce(sum(precio_catalogo * cantidad),0)
    into v_lineas, v_catalogo_total
    from pg_temp.pth_deuda_lineas;
  v_neto := coalesce(v_pedido.total,0) - coalesce(v_pedido.costo_mensajeria,0);

  for r in select * from pg_temp.pth_deuda_lineas order by linea loop
    v_incidencia := null;
    if trim(coalesce(v_pedido.producto,'')) = '' then
      v_precio_unit := null;
      v_incidencia := 'Pedido sin producto analizable';
    elsif v_formato_invalido then
      v_precio_unit := null;
      v_incidencia := 'Formato de producto no analizable';
    elsif v_lineas = 1 then
      v_precio_unit := round(v_neto / greatest(r.cantidad,1), 2);
    elsif r.precio_catalogo is null or v_catalogo_total <= 0 then
      v_precio_unit := null;
      v_incidencia := 'Producto de pedido mixto no encontrado en catálogo';
    else
      v_precio_unit := round((v_neto * (r.precio_catalogo * r.cantidad) / v_catalogo_total) / r.cantidad, 2);
    end if;

    if v_precio_unit is null or v_precio_unit < 0 then
      v_tarifa_unit := null;
      v_incidencia := coalesce(v_incidencia,'Precio unitario inválido');
    else
      v_tarifa_unit := public.tarifa_sistema_por_unidad(v_precio_unit);
    end if;

    insert into public.deuda_sistema_detalle(
      pedido_id,linea,orden_dia,fecha_pedido,producto,cantidad,
      precio_unitario,tarifa_unitaria,tarifa_total,estado,incidencia
    ) values (
      v_pedido.id,r.linea,v_pedido.orden_dia,v_pedido.fecha,r.producto,r.cantidad,
      v_precio_unit,v_tarifa_unit,
      case when v_tarifa_unit is null then null else round(v_tarifa_unit*r.cantidad,2) end,
      case when v_incidencia is null then 'pendiente' else 'incidencia' end,
      v_incidencia
    ) on conflict (pedido_id,linea) do nothing;
  end loop;

  return v_lineas;
end;
$function$;

create or replace function public.trigger_materializar_deuda_sistema()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $function$
begin
  perform pg_advisory_xact_lock(hashtext('pth_liquidar_deuda_sistema'));

  if old.estado = 'Entregado' and new.estado <> 'Entregado' then
    delete from public.deuda_sistema_detalle
    where pedido_id=new.id and estado in ('pendiente','incidencia') and liquidacion_id is null;
    return new;
  end if;

  if new.estado = 'Entregado' and (
    old.estado is distinct from 'Entregado'
    or old.total is distinct from new.total
    or old.costo_mensajeria is distinct from new.costo_mensajeria
    or old.producto is distinct from new.producto
  ) then
    delete from public.deuda_sistema_detalle
    where pedido_id=new.id and estado in ('pendiente','incidencia') and liquidacion_id is null;
    perform public.materializar_deuda_sistema_pedido(new.id);
  end if;
  return new;
end;
$function$;

drop trigger if exists a_materializar_deuda_sistema on public.pedidos;
create trigger a_materializar_deuda_sistema
after update of estado, total, costo_mensajeria, producto on public.pedidos
for each row execute function public.trigger_materializar_deuda_sistema();

create or replace function public.reconstruir_deuda_sistema_pendiente()
returns integer
language plpgsql
security definer
set search_path = public, pg_temp
as $function$
declare
  r record;
  v_total integer := 0;
begin
  for r in
    select p.id from public.pedidos p
    where p.estado = 'Entregado'
      and coalesce(lower(trim(p.pago_sistema)), 'pendiente') <> 'pagado'
    order by p.fecha, p.id
  loop
    v_total := v_total + public.materializar_deuda_sistema_pedido(r.id);
  end loop;
  return v_total;
end;
$function$;

