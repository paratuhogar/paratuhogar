create or replace function public.validar_deuda_sistema_integridad()
returns jsonb
language plpgsql
security definer
stable
set search_path = public, pg_temp
as $function$
declare
  v_faltantes integer;
  v_no_entregados integer;
  v_incidencias integer;
  v_pedidos integer;
  v_lineas integer;
  v_total numeric(12,2);
  v_control numeric(12,2);
begin
  select count(*) into v_faltantes
  from public.pedidos p
  where p.estado='Entregado'
    and coalesce(lower(trim(p.pago_sistema)),'pendiente') <> 'pagado'
    and not exists (
      select 1 from public.deuda_sistema_detalle d
      where d.pedido_id=p.id and d.estado in ('pendiente','incidencia')
    );

  select count(*) into v_no_entregados
  from public.deuda_sistema_detalle d
  join public.pedidos p on p.id=d.pedido_id
  where d.estado in ('pendiente','incidencia') and p.estado <> 'Entregado';

  select
    count(distinct pedido_id) filter (where estado='pendiente'),
    count(*) filter (where estado='pendiente'),
    count(*) filter (where estado='incidencia'),
    coalesce(sum(tarifa_total) filter (where estado='pendiente'),0)
  into v_pedidos,v_lineas,v_incidencias,v_total
  from public.deuda_sistema_detalle
  where estado in ('pendiente','incidencia');

  if v_faltantes > 0 or v_no_entregados > 0 or v_incidencias > 0 then
    raise exception 'Integridad de deuda inválida: faltantes %, no entregados %, incidencias %',
      v_faltantes,v_no_entregados,v_incidencias;
  end if;

  if exists (
    select 1 from public.pedidos p join public.deuda_sistema_detalle d on d.pedido_id=p.id
    where p.orden_dia='CA-1247' and d.estado='pendiente'
  ) then
    select sum(d.tarifa_total) into v_control
    from public.deuda_sistema_detalle d join public.pedidos p on p.id=d.pedido_id
    where p.orden_dia='CA-1247' and d.estado='pendiente';
    if v_control <> 3.00 then raise exception 'Control CA-1247 inválido: %',v_control; end if;
  end if;
  if exists (
    select 1 from public.pedidos p join public.deuda_sistema_detalle d on d.pedido_id=p.id
    where p.orden_dia='CA-1324' and d.estado='pendiente'
  ) then
    select sum(d.tarifa_total) into v_control
    from public.deuda_sistema_detalle d join public.pedidos p on p.id=d.pedido_id
    where p.orden_dia='CA-1324' and d.estado='pendiente';
    if v_control <> 1.00 then raise exception 'Control CA-1324 inválido: %',v_control; end if;
  end if;

  return jsonb_build_object('pedidos',v_pedidos,'lineas',v_lineas,'incidencias',v_incidencias,'total',v_total);
end;
$function$;

create or replace function public.liquidar_deuda_sistema(
  p_admin_id uuid,
  p_password text,
  p_referencia text default null
)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $function$
declare
  v_id uuid;
  v_total numeric(12,2);
  v_pedidos integer;
  v_lineas integer;
  v_admin text;
begin
  if not public.es_admin_boveda(p_admin_id,p_password) then
    raise exception 'Acceso reservado a administradores de la Bóveda';
  end if;

  -- Respeta el mismo orden de bloqueos que el trigger: primero pedidos y
  -- después el advisory lock. Evita un ciclo pedido -> advisory / advisory -> pedido.
  perform 1
    from public.pedidos p
   where exists (
     select 1 from public.deuda_sistema_detalle d
      where d.pedido_id=p.id and d.estado='pendiente'
   )
   order by p.id
   for update;

  perform pg_advisory_xact_lock(hashtext('pth_liquidar_deuda_sistema'));

  if exists (select 1 from public.deuda_sistema_detalle where estado='incidencia') then
    raise exception 'Existen incidencias contables pendientes; no se puede liquidar';
  end if;

  perform 1 from public.deuda_sistema_detalle where estado='pendiente' for update;
  select coalesce(sum(tarifa_total),0),count(distinct pedido_id),count(*)
    into v_total,v_pedidos,v_lineas
    from public.deuda_sistema_detalle
   where estado='pendiente';
  if v_lineas = 0 then raise exception 'No existe deuda pendiente para liquidar'; end if;

  select coalesce((select nombre from public.gestores where id=p_admin_id),'Ángel (Dueño)') into v_admin;
  insert into public.liquidaciones_sistema(total,pedidos_count,lineas_count,admin_id,admin_nombre,referencia)
  values(v_total,v_pedidos,v_lineas,p_admin_id,v_admin,nullif(trim(p_referencia),'')) returning id into v_id;

  insert into public.liquidaciones_sistema_detalle(liquidacion_id,deuda_detalle_id,pedido_id,tarifa_total)
  select v_id,id,pedido_id,tarifa_total from public.deuda_sistema_detalle where estado='pendiente';

  update public.deuda_sistema_detalle
     set estado='liquidado',liquidacion_id=v_id,liquidado_en=now()
   where estado='pendiente';

  update public.pedidos p set pago_sistema='Pagado'
   where exists (
     select 1 from public.liquidaciones_sistema_detalle ld
     where ld.liquidacion_id=v_id and ld.pedido_id=p.id
   );

  return jsonb_build_object('id',v_id,'total',v_total,'pedidos',v_pedidos,'lineas',v_lineas);
end;
$function$;

-- La reconstrucción histórica mantiene intactos los pedidos ya pagados.
