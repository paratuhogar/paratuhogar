// Función auxiliar para copiar el guion y dar feedback visual
function copiarGuionVip(btnElement) {
    const textarea = document.getElementById('guion-vip-text');
    textarea.select();
    navigator.clipboard.writeText(textarea.value).then(() => {
        const originalText = btnElement.innerHTML;
        btnElement.innerHTML = `<span class="material-symbols-outlined text-[14px]">check</span> ¡Copiado!`;
        btnElement.classList.replace('bg-indigo-600', 'bg-emerald-500');
        btnElement.classList.replace('hover:bg-indigo-500', 'hover:bg-emerald-400');
        
        setTimeout(() => {
            btnElement.innerHTML = originalText;
            btnElement.classList.replace('bg-emerald-500', 'bg-indigo-600');
            btnElement.classList.replace('hover:bg-emerald-400', 'hover:bg-indigo-500');
        }, 2000);
    });
}