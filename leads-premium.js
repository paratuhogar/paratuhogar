function cerrarPromoLeads() {
    const modal = document.getElementById('modal-promo-leads');
    if (modal) modal.remove();
    localStorage.setItem('pth_promo_leads_vista', 'true');
    
    // EFECTO DOMINÓ: Al cerrar los Leads, abrimos el de Tráfico (El último de la cadena)
    setTimeout(() => {
        if (typeof TrafficCampaign !== 'undefined' && TrafficCampaign.showMissionModal) {
            TrafficCampaign.showMissionModal();
        }
    }, 500);
}
