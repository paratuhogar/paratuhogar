function generarContactosVCF(nombreGestor, leadsArray) {
    let vcfContent = "";
    
    leadsArray.forEach((numero, index) => {
        const numLimpio = numero.replace(/\s+/g, ''); // Quita espacios extra
        vcfContent += "BEGIN:VCARD\n";
        vcfContent += "VERSION:3.0\n";
        // Nombre del contacto: ej. "⭐ Cliente VIP 1"
        vcfContent += `FN:⭐ Cliente VIP ${index + 1}\n`;
        vcfContent += `TEL;TYPE=CELL:${numLimpio}\n`;
        vcfContent += "END:VCARD\n";
    });

    // Crear el archivo .vcf
    const blob = new Blob([vcfContent], { type: "text/vcard;charset=utf-8" });
    const link = document.createElement("a");
    link.href = URL.createObjectURL(blob);
    link.download = `Contactos_VIP_${nombreGestor.replace(/\s+/g, '_')}.vcf`;
    
    // Descargar
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);

    // Mostrar el panel de éxito con instrucciones (reemplaza al viejo alert)
    mostrarPanelExitoVCF(nombreGestor);

}

