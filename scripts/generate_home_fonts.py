#!/usr/bin/env python3
"""Vendor the existing Google fonts unchanged; pin unused icon stroke weights."""
import hashlib
import json
from pathlib import Path
import re
from urllib.request import Request, urlopen

ROOT = Path(__file__).resolve().parents[1]
DESTINATION = ROOT / 'assets/fonts'
USER_AGENT = 'Mozilla/5.0 (Linux; Android 11; moto g power (2022)) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/136.0.0.0 Mobile Safari/537.36'
SOURCES = [
    'https://fonts.googleapis.com/css2?family=Manrope:wght@300;400;500;700;800&family=Rajdhani:wght@400;500;600;700&display=swap',
    # The app uses wght400 everywhere; retain the complete FILL axis and all icons.
    'https://fonts.googleapis.com/css2?family=Material+Symbols+Outlined:wght,FILL@400,0..1&display=swap',
]


def download(url):
    with urlopen(Request(url, headers={'User-Agent': USER_AGENT}), timeout=60) as response:
        return response.read()


def main():
    DESTINATION.mkdir(parents=True, exist_ok=True)
    output, files, known = [], [], {}
    for source in SOURCES:
        css = download(source).decode('utf-8')
        if '@font-face' not in css:
            raise ValueError('Google Fonts no devolvió una hoja de fuentes válida')
        for block in re.findall(r'@font-face\s*\{[^}]+\}', css):
            family = re.search(r"font-family:\s*'([^']+)'", block)[1]
            for url in re.findall(r'url\((https://fonts\.gstatic\.com/[^)]+\.woff2)\)', block):
                if url in known:
                    continue
                content = download(url)
                if not content.startswith(b'wOF2') or len(content) > 500000:
                    raise ValueError('Fuente WOFF2 inválida o sin optimizar')
                digest = hashlib.sha256(content).hexdigest()
                name = f'pth-{digest[:16]}.woff2'
                (DESTINATION / name).write_bytes(content)
                local = '/assets/fonts/' + name
                known[url] = local
                files.append({'family': family, 'source': url, 'local': local, 'sha256': digest, 'bytes': len(content), 'latin': 'U+0000-00FF' in block})
        for url, local in known.items():
            css = css.replace(url, local)
        if 'url(https:' in css:
            raise ValueError('Queda una fuente externa sin verificar')
        output.append(css)
    licenses = {
        'Rajdhani-OFL.txt': 'https://raw.githubusercontent.com/google/fonts/main/ofl/rajdhani/OFL.txt',
        'Material-Symbols-LICENSE.txt': 'https://raw.githubusercontent.com/google/material-design-icons/master/LICENSE',
    }
    for name, url in licenses.items():
        license_text = download(url).decode('utf-8')
        (DESTINATION / name).write_text('\n'.join(line.rstrip() for line in license_text.splitlines()) + '\n', encoding='utf-8')
    (ROOT / 'css/home-fonts.css').write_text('/* Generated by scripts/generate_home_fonts.py; source/licences: assets/fonts. */\n' + '\n'.join(output), encoding='utf-8')
    (DESTINATION / 'home-font-sources.json').write_text(json.dumps({'css_sources': SOURCES, 'files': files}, indent=2) + '\n', encoding='utf-8')
    print(json.dumps({'files': len(files), 'bytes': sum(f['bytes'] for f in files), 'preload': next(f['local'] for f in files if f['family'] == 'Manrope' and f['latin'])}))


if __name__ == '__main__':
    main()
